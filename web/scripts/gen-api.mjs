// Generates TypeScript types from the shared contracts:
//   ../contracts/public.yaml         -> <outDir>/schema.d.ts  (openapi-typescript)
//   ../contracts/report.schema.json  -> <outDir>/report.d.ts  (json-schema-to-typescript)
//   ../contracts/public.yaml         -> <outDir>/operations.ts (operationId -> method + path)
// Usage: node scripts/gen-api.mjs <outDir>
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { compile } from 'json-schema-to-typescript';
import { parse as parseYaml } from 'yaml';

const contracts = fileURLToPath(new URL('../../contracts/', import.meta.url));
const banner = (source) =>
  `// GENERATED by \`npm run gen:api\` from contracts/${source}. Do not edit by hand.\n\n`;

export async function generate(outDir) {
  mkdirSync(outDir, { recursive: true });

  const publicYaml = join(contracts, 'public.yaml');
  const ast = await openapiTS(new URL(`file://${publicYaml}`));
  writeFileSync(join(outDir, 'schema.d.ts'), banner('public.yaml') + astToString(ast));

  const doc = parseYaml(readFileSync(publicYaml, 'utf8'));
  const lines = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of ['get', 'put', 'post', 'delete']) {
      if (item[method]) lines.push(`  ${item[method].operationId}: { method: '${method.toUpperCase()}', path: '${path}' },`);
    }
  }
  writeFileSync(
    join(outDir, 'operations.ts'),
    banner('public.yaml') + `export const operations = {\n${lines.join('\n')}\n} as const;\n\nexport type OperationId = keyof typeof operations;\n`,
  );

  const schema = JSON.parse(readFileSync(join(contracts, 'report.schema.json'), 'utf8'));
  const report = await compile(tuplesToDraft7(schema), 'IntermissionRunReport', {
    bannerComment: '',
    additionalProperties: false,
    cwd: contracts,
    style: { singleQuote: true },
  });
  writeFileSync(join(outDir, 'report.d.ts'), banner('report.schema.json') + report);
}

// json-schema-to-typescript does not understand 2020-12 `prefixItems`; rewrite tuples to the
// equivalent draft-07 form (in memory only) so curves type as [number, number][].
function tuplesToDraft7(node) {
  if (Array.isArray(node)) return node.map(tuplesToDraft7);
  if (node === null || typeof node !== 'object') return node;
  const out = Object.fromEntries(Object.entries(node).map(([k, v]) => [k, tuplesToDraft7(v)]));
  if (out.prefixItems) {
    out.items = out.prefixItems;
    out.additionalItems = false;
    delete out.prefixItems;
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outDir = process.argv[2];
  if (!outDir) {
    console.error('usage: node scripts/gen-api.mjs <outDir>');
    process.exit(2);
  }
  await generate(resolve(outDir));
  console.log(`wrote schema.d.ts, report.d.ts and operations.ts to ${outDir}`);
}
